//! Rewrites the branding the engine stamps into an exported G-code file.
//!
//! Ported from `src/qt/src/GcodeBrand.cpp`. The engine hardcodes its own
//! application name in the first line, in the JSON producer fields, and in the
//! delimiters of the two config blocks it appends; all of them become this
//! application's name, and every config key and value inside those blocks is left
//! byte-identical.

use std::path::Path;
use std::time::{SystemTime, UNIX_EPOCH};

use sha2::{Digest, Sha256};

const PRODUCT_NAME: &str = "next-layer";
const LAYER_COUNT_KEY: &str = "; total layers count = ";
const ESTIMATED_TIME_KEY: &str = "; estimated printing time (normal mode) = ";
const BLOCK_KEYS: [&str; 2] = ["_json_config = ", "_config = "];

/// The version this build stamps into G-code and shows in the window.
pub fn application_version() -> String {
    crate::BAKED_VERSION.to_owned()
}

/// Rewrites the file at `path`.
///
/// Returns the number of lines rewritten, or -1 when the file cannot be read or
/// written. Idempotent: a file that is already branded is only touched where the
/// version line differs.
///
/// `configuration_json`, when given, is the resolved settings document the slice
/// was handed: it is appended as one metadata block, so the file records the
/// settings it was printed with.
pub fn brand_gcode(path: &str, configuration_json: &str) -> i32 {
    let Ok(bytes) = std::fs::read(path) else {
        return -1;
    };
    let text = String::from_utf8_lossy(&bytes);
    let lines: Vec<&str> = text.split('\n').collect();
    let layers = lines
        .iter()
        .filter(|line| line.starts_with(";LAYER_CHANGE"))
        .count();

    let stamp = utc_stamp();
    let mut changed = 0;
    let mut rewritten: Vec<String> = Vec::with_capacity(lines.len() + 4);
    let mut layer_count_written = layers == 0;
    for original in &lines {
        let mut line = (*original).to_owned();
        if line.starts_with(';') {
            if rewrite_line(&mut line, &stamp) {
                changed += 1;
            }
        }
        if !layer_count_written && line.starts_with(ESTIMATED_TIME_KEY) {
            rewritten.push(format!("{LAYER_COUNT_KEY}{layers}"));
            layer_count_written = true;
            changed += 1;
        }
        rewritten.push(line);
    }

    if !layer_count_written && layers > 0 {
        rewritten.push(format!("{LAYER_COUNT_KEY}{layers}"));
        changed += 1;
    }

    let metadata = configuration_json.trim();
    if !metadata.is_empty() {
        rewritten.push(format!("; {PRODUCT_NAME}_config = begin"));
        rewritten.push(format!(
            "; {PRODUCT_NAME}_config = {{\"producer\": \"{PRODUCT_NAME}\", \
             \"producer_version\": \"{}\", \"configuration\": {metadata}}}",
            application_version()
        ));
        rewritten.push(format!("; {PRODUCT_NAME}_config = end"));
        changed += 1;
    }

    if changed == 0 {
        return 0;
    }

    let body = rewritten.join("\n");
    match std::fs::write(path, body.as_bytes()) {
        Ok(()) => changed,
        Err(_) => -1,
    }
}

/// sha256 of a toolpath's move and command lines, comments left out: the same
/// slice run twice differs in its timestamp and UUIDs and nowhere else, so this is
/// what two runs are compared by.
pub fn toolpath_digest(path: &str) -> String {
    let Ok(bytes) = std::fs::read(path) else {
        return "unreadable".to_owned();
    };
    let mut hash = Sha256::new();
    for line in bytes.split_inclusive(|byte| *byte == b'\n') {
        if line.first().is_some_and(|first| *first == b';') {
            continue;
        }
        hash.update(line);
    }
    hash.finalize()
        .iter()
        .map(|byte| format!("{byte:02x}"))
        .collect()
}

fn rewrite_line(line: &mut String, stamp: &str) -> bool {
    if line.starts_with("; generated by ") {
        let replacement = format!(
            "; generated by {PRODUCT_NAME} {} on {stamp} UTC",
            application_version()
        );
        if *line != replacement {
            *line = replacement;
            return true;
        }
        return false;
    }

    let producer = "\"producer\": \"PrusaSlicer\"";
    if line.contains(producer) {
        *line = line.replace(producer, &format!("\"producer\": \"{PRODUCT_NAME}\""));
        return true;
    }

    let version_key = "\"producer_version\": \"";
    if let Some(found) = line.find(version_key) {
        let start = found + version_key.len();
        if let Some(end) = line[start..].find('"').map(|at| at + start) {
            let version = application_version();
            line.replace_range(start..end, &version);
            return true;
        }
    }

    if !line.starts_with("; ") {
        return false;
    }
    for key in BLOCK_KEYS {
        let Some(at) = line.find(key) else {
            continue;
        };
        if at <= 2 || line[2..at].contains(' ') {
            continue;
        }
        line.replace_range(0..at, &format!("; {PRODUCT_NAME}"));
        return true;
    }

    false
}

fn utc_stamp() -> String {
    let seconds = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|since| since.as_secs() as i64)
        .unwrap_or_default();
    utc_stamp_at(seconds)
}

fn utc_stamp_at(seconds: i64) -> String {
    let (year, month, day) = civil_from_days(seconds.div_euclid(86_400));
    let second_of_day = seconds.rem_euclid(86_400);
    format!(
        "{year:04}-{month:02}-{day:02} at {:02}:{:02}:{:02}",
        second_of_day / 3600,
        (second_of_day % 3600) / 60,
        second_of_day % 60
    )
}

fn civil_from_days(days: i64) -> (i64, u32, u32) {
    let shifted = days + 719_468;
    let era = if shifted >= 0 { shifted } else { shifted - 146_096 } / 146_097;
    let day_of_era = (shifted - era * 146_097) as u64;
    let year_of_era =
        (day_of_era - day_of_era / 1460 + day_of_era / 36_524 - day_of_era / 146_096) / 365;
    let year = year_of_era as i64 + era * 400;
    let day_of_year = day_of_era - (365 * year_of_era + year_of_era / 4 - year_of_era / 100);
    let month_position = (5 * day_of_year + 2) / 153;
    let day = (day_of_year - (153 * month_position + 2) / 5 + 1) as u32;
    let month = if month_position < 10 {
        month_position + 3
    } else {
        month_position - 9
    } as u32;
    (if month <= 2 { year + 1 } else { year }, month, day)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn written(name: &str, body: &str) -> String {
        let path = std::env::temp_dir().join(format!(
            "next-layer-brand-{}-{name}.gcode",
            std::process::id()
        ));
        std::fs::write(&path, body).expect("a scratch toolpath");
        path.to_string_lossy().into_owned()
    }

    #[test]
    fn a_stamp_is_the_reference_slicers_shape() {
        assert_eq!(utc_stamp_at(0), "1970-01-01 at 00:00:00");
        assert_eq!(utc_stamp_at(1_700_000_000), "2023-11-14 at 22:13:20");
        assert_eq!(utc_stamp_at(951_782_400), "2000-02-29 at 00:00:00");
    }

    #[test]
    fn branding_rewrites_the_header_and_appends_the_settings() {
        let path = written(
            "brand",
            "; generated by PrusaSlicer 2.9.0 on 2024-01-01 at 00:00:00 UTC\n\
             ;LAYER_CHANGE\n;\n; estimated printing time (normal mode) = 5m\n\
             ; generated by PrusaSlicer, {\"producer\": \"PrusaSlicer\"}\n\
             G1 X1 Y2\n",
        );
        let changed = brand_gcode(&path, "{\"layer_height\": 0.2}");
        let body = std::fs::read_to_string(&path).expect("the branded file");
        let _ = std::fs::remove_file(&path);

        assert_eq!(changed, 4);
        assert!(body.contains("; generated by next-layer "));
        assert!(body.contains("; total layers count = 1\n"));
        assert!(!body.contains("PrusaSlicer"));
        assert!(body.contains(
            "; next-layer_config = {\"producer\": \"next-layer\", \"producer_version\": \
             \"0.1.2\", \"configuration\": {\"layer_height\": 0.2}}\n\
             ; next-layer_config = end"
        ));
    }

    #[test]
    fn a_file_with_nothing_to_rewrite_is_left_untouched() {
        let path = written("clean", "G1 X1\nG1 X2\n");
        assert_eq!(brand_gcode(&path, ""), 0);
        let body = std::fs::read_to_string(&path).expect("the untouched file");
        let _ = std::fs::remove_file(&path);
        assert_eq!(body, "G1 X1\nG1 X2\n");
    }

    #[test]
    fn a_digest_ignores_comments_and_everything_a_second_run_changes() {
        let first = written("digest-a", "; generated by a\nG1 X1\n;LAYER_CHANGE\nM104 S200\n");
        let second = written("digest-b", "; generated by b\nG1 X1\n;LAYER_CHANGE\nM104 S200\n");
        let other = written("digest-c", "; generated by b\nG1 X1\n;LAYER_CHANGE\nM104 S210\n");
        let digest = |path: &str| toolpath_digest(path);

        assert_eq!(digest(&first), digest(&second));
        assert_ne!(digest(&first), digest(&other));
        assert_eq!(digest(&first).len(), 64);
        assert_eq!(digest("/nonexistent/next-layer"), "unreadable");
        for path in [first, second, other] {
            let _ = std::fs::remove_file(path);
        }
    }

    #[test]
    fn a_digest_is_the_sha256_of_the_lines_it_kept() {
        let path = written("digest-known", ";comment\nG1 X0\n");
        let digest = toolpath_digest(&path);
        let _ = std::fs::remove_file(&path);
        assert_eq!(
            digest,
            "260a9b6a75053701b52c71e736fa9c71642365be51055031126806f5b73117d3"
        );
    }
}
