#include "GcodeBrand.hpp"

#include <QFile>
#include <QStringList>

#ifndef NEXT_LAYER_VERSION
#define NEXT_LAYER_VERSION "0.1.0"
#endif

namespace next_layer {

namespace {

constexpr const char* kProductName = "next-layer";

bool rewriteLine(QString& line, int& changed)
{
    if (line.startsWith(QStringLiteral("; generated by "))) {
        const QString replacement = QStringLiteral("; generated by %1 %2")
                                        .arg(QLatin1String(kProductName), applicationVersion());
        if (line != replacement) {
            line = replacement;
            ++changed;
        }
        return true;
    }

    if (line.contains(QStringLiteral("\"producer\": \"PrusaSlicer\""))) {
        line.replace(QStringLiteral("\"producer\": \"PrusaSlicer\""),
                     QStringLiteral("\"producer\": \"%1\"").arg(QLatin1String(kProductName)));
        ++changed;
        return true;
    }

    const QString versionKey = QStringLiteral("\"producer_version\": \"");
    if (line.contains(versionKey)) {
        const int start = line.indexOf(versionKey) + versionKey.size();
        const int end = line.indexOf(QLatin1Char('"'), start);
        if (end > start) {
            line.replace(start, end - start, applicationVersion());
            ++changed;
            return true;
        }
    }

    static const QStringList blockKeys{QStringLiteral("_json_config = "),
                                       QStringLiteral("_config = ")};
    if (line.startsWith(QStringLiteral("; "))) {
        for (const QString& key : blockKeys) {
            const int at = line.indexOf(key);
            if (at > 2 && !line.mid(2, at - 2).contains(QLatin1Char(' '))) {
                line.replace(0, at, QStringLiteral("; next-layer"));
                ++changed;
                return true;
            }
        }
    }

    return false;
}

}

QString applicationVersion()
{
    return QStringLiteral(NEXT_LAYER_VERSION);
}

int brandGcode(const QString& path)
{
    QFile file(path);
    if (!file.open(QIODevice::ReadOnly | QIODevice::Text))
        return -1;

    const QStringList lines = QString::fromUtf8(file.readAll()).split(QLatin1Char('\n'));
    file.close();

    QStringList rewritten;
    rewritten.reserve(lines.size());
    int changed = 0;
    for (const QString& original : lines) {
        QString line = original;
        if (line.startsWith(QLatin1Char(';')))
            rewriteLine(line, changed);
        rewritten.append(line);
    }

    if (changed == 0)
        return 0;

    if (!file.open(QIODevice::WriteOnly | QIODevice::Truncate))
        return -1;
    const QByteArray body = rewritten.join(QLatin1Char('\n')).toUtf8();
    const bool written = file.write(body) == body.size();
    file.close();
    return written ? changed : -1;
}

}
